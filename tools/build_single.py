#!/usr/bin/env python3
"""Bundle modules + www assets into dist/main_single.py.

    python tools/build_single.py

The web assets are stored as base64 comment lines at the end of the file, so
MicroPython's compiler skips them and they cost no RAM. On first boot the
firmware reads its own main.py, writes the assets to flash, then sets a marker
in data/ so later boots skip the scan.

Upload the result as `main.py`. For the ESP32 family only; ESP8266 cannot fit
this firmware (see README).
"""
import base64
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
FW = os.path.join(ROOT, 'firmware', 'esp32')
OUT = os.path.join(ROOT, 'dist', 'main_single.py')

MODULES = ['settings.py', 'effects.py', 'stylelib.py', 'engine.py', 'httpd.py', 'main.py']

SIBLING = re.compile(
    r'^\s*(from\s+(settings|effects|stylelib|engine|httpd)\s+import\s+.*'
    r'|import\s+(settings|effects|stylelib|engine|httpd)\s*)$')

MARK = '#@@WSASSET '
CHUNK = 96

INSTALLER = '''
# ===== first-boot asset installer =====
_WS_MARK = b'#@@WSASSET '


def _install_assets():
    try:
        os.stat('data/.assets_v1')
        return
    except OSError:
        pass
    try:
        os.mkdir('data')
    except OSError:
        pass
    try:
        os.mkdir('www')
    except OSError:
        pass
    try:
        os.mkdir('styles')
    except OSError:
        pass
    try:
        src = open('main.py', 'rb')
    except OSError:
        return
    out = None
    try:
        while True:
            line = src.readline()
            if not line:
                break
            if line.startswith(_WS_MARK):
                if out:
                    out.close()
                    out = None
                parts = line[len(_WS_MARK):].split(b' ')
                if len(parts) < 3:
                    continue
                path = parts[0].decode() + '/' + parts[1].decode()
                try:
                    os.stat(path)
                    continue
                except OSError:
                    pass
                try:
                    out = open(path, 'wb')
                except OSError:
                    out = None
                continue
            if out and line.startswith(b'#'):
                try:
                    out.write(ubinascii.a2b_base64(line[1:].strip()))
                except Exception:
                    pass
    finally:
        if out:
            out.close()
        src.close()
    try:
        f = open('data/.assets_v1', 'w')
        f.write('1')
        f.close()
    except OSError:
        pass
'''


def read(path):
    with open(path, 'r', encoding='utf-8') as f:
        return f.read()


def strip_siblings(src):
    out = []
    for line in src.splitlines(True):
        if SIBLING.match(line.rstrip('\n')):
            continue
        out.append(line)
    return ''.join(out)


def collect_assets():
    files = []
    for sub in ('www', 'styles'):
        base = os.path.join(FW, sub)
        for name in sorted(os.listdir(base)):
            p = os.path.join(base, name)
            if os.path.isfile(p) and (sub == 'www' or
                                      name.endswith('.json') or name.endswith('.py')):
                files.append((sub, name, read(p)))
    return files


def blob(files):
    lines = []
    for sub, name, text in files:
        raw = text.encode('utf-8')
        enc = base64.b64encode(raw).decode('ascii')
        lines.append('%s%s %s %d' % (MARK, sub, name, len(raw)))
        for i in range(0, len(enc), CHUNK):
            lines.append('#' + enc[i:i + CHUNK])
    return '\n'.join(lines) + '\n'


def build():
    parts = ['# Auto-generated by tools/build_single.py - do not edit.\n',
             '# ESP Web WS2812B single-file build.\n',
             '# Author: 洋洋柚 (Bilibili/Douyin: 洋洋柚Y) - CC BY-NC-SA 4.0 (NonCommercial)\n',
             '# https://github.com/YangYangyou-Zhang/esp_web_ws2812b_micropython\n',
             '# https://gitee.com/zhangyangyangyou/esp_web_ws2812b_micropython\n\n',
             'import ubinascii\n']
    for name in MODULES:
        src = strip_siblings(read(os.path.join(FW, name)))
        parts.append('\n# ===== %s =====\n' % name)
        if name == 'main.py':
            src = src.split("if __name__ == '__main__'")[0]
        parts.append(src)
    parts.append(INSTALLER)
    parts.append('\n_install_assets()\n\nif __name__ == \'__main__\':\n    run()\n\n')
    files = collect_assets()
    parts.append(blob(files))
    text = ''.join(parts)
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, 'w', encoding='utf-8') as f:
        f.write(text)
    print('wrote %s (%d bytes, %d assets/styles)' % (
        OUT, len(text.encode('utf-8')), len(files)))
    try:
        compile(text, OUT, 'exec')
        print('syntax check: ok')
    except SyntaxError as e:
        print('syntax check failed:', e)
        return 1
    return 0


if __name__ == '__main__':
    sys.exit(build())
